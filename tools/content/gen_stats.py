#!/usr/bin/env python3
"""Write docs/stats.json for Higher or lower ("Which is bigger?").

Country population + area items come from docs/data/countries.json (best-known countries,
tier 1-2; ids popXX / areaXX by ISO code); everything else is hand-made in stats_src.py.
    python3 tools/content/gen_stats.py && python3 validate.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, HERE)
import stats_src as S  # noqa: E402


# Names that take "the" in a sentence ("bigger than the Netherlands", "after the Eiffel Tower").
# Written out as item["s"] (sentence form) only where it differs from the name; every river gets one.
THE = {
    # countries
    "Bahamas", "Netherlands", "Philippines", "United Arab Emirates", "United Kingdom", "United States",
    "Dominican Republic", "Central African Republic", "DR Congo", "Republic of the Congo", "Gambia",
    "Maldives", "Marshall Islands", "Solomon Islands", "Comoros", "Seychelles",
    # peaks, towers, buildings, islands
    "Matterhorn", "Shanghai Tower", "Makkah Royal Clock Tower", "Ping An Finance Centre", "Lotte World Tower",
    "CN Tower", "International Commerce Centre", "Lakhta Center", "Petronas Towers", "Willis Tower",
    "Empire State Building", "Berlin TV Tower", "Eiffel Tower", "Space Needle", "Washington Monument",
    "Blackpool Tower", "London Eye", "Statue of Liberty", "Leaning Tower of Pisa", "Burj Al Arab",
    "Chrysler Building", "Great Pyramid of Giza", "White Tower, Tower of London", "Forbidden City",
    "Suez Canal", "Brooklyn Bridge", "Tower Bridge", "Panama Canal", "Hoover Dam", "Golden Gate Bridge",
    "Atomium", "Sydney Opera House", "Louvre Pyramid", "Channel Tunnel", "South Island", "North Island",
    "Isle of Man", "Isle of Wight",
}


def sentence_name(cat, name):
    return "the " + name if cat == "river" or name in THE else None


def main():
    countries = json.load(open(os.path.join(ROOT, "docs", "data", "countries.json"), encoding="utf-8"))
    items = []
    for c in countries:
        if c["tier"] > 2:
            continue
        if c.get("pop_m"):
            items.append({"id": "pop" + c["iso2"], "c": "pop", "n": c["name"], "v": c["pop_m"], "d": c["continent"],
                          "note": "UN estimate for %d, rounded" % c.get("pop_year", 2024)})
        if c.get("area_km2"):
            items.append({"id": "area" + c["iso2"], "c": "area", "n": c["name"], "v": c["area_km2"], "d": c["continent"],
                          "note": S.AREA_NOTE.get(c["iso2"], "Total area, rounded")})
    for cat, rows in S.HAND.items():
        for r in rows:
            it = {"id": r[0], "c": cat, "n": r[1], "v": r[2], "d": r[3], "note": r[4]}
            if len(r) > 5 and "ap" in r[5]:
                it["ap"] = True
            items.append(it)
    for it in items:
        sn = sentence_name(it["c"], it["n"])
        if sn:
            it["s"] = sn
    known = {i["n"] for i in items}
    missing = sorted(n for n in THE if n not in known and n not in {c["name"] for c in countries})
    if missing:
        print("note: THE names not in the data:", missing)
    doc = {"about": "Higher or lower data. Generated by tools/content/gen_stats.py: country populations "
                    "(UN 2024 estimates, millions) and areas from docs/data/countries.json, the rest hand-made "
                    "in tools/content/stats_src.py. Values are rounded; 'ap' items are approximate; years < 0 are BC.",
           "cats": S.CATS, "items": items}
    out = os.path.join(ROOT, "docs", "stats.json")
    with open(out, "w", encoding="utf-8") as f:
        f.write(json.dumps(doc, indent=0, ensure_ascii=False) + "\n")
    per = {}
    for i in items:
        per[i["c"]] = per.get(i["c"], 0) + 1
    print(len(items), "items", per, "->", os.path.normpath(out))


if __name__ == "__main__":
    main()
