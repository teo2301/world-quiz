#!/usr/bin/env python3
"""Write docs/clues.json for Guess the country (internal mode id "career") from clues_src.py.

Each item: id (c + iso2), n (the answer, as in countries.json), al (accepted other names:
countries.json aliases + the extra ones in clues_src), clues (exactly 5, hardest first,
the capital last). `decoys` = every other country name/alias in countries.json plus
EXTRA_DECOYS: a guess that IS one of those never counts as a typo of an answer.
    python3 tools/content/gen_clues.py && python3 validate.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "server"))
import modes  # noqa: E402
from clues_src import C, EXTRA_DECOYS  # noqa: E402


def main():
    countries = json.load(open(os.path.join(ROOT, "docs", "data", "countries.json"), encoding="utf-8"))
    by_name = {c["name"]: c for c in countries}
    items, used = [], set()
    for name, extra, clues, cap in C:
        c = by_name[name]                       # KeyError = name not as in countries.json
        if name in used:
            raise SystemExit("duplicate " + name)
        used.add(name)
        if len(clues) != 4:
            raise SystemExit(name + ": need 4 clues + the capital")
        if cap is None:
            if not c.get("capital"):
                raise SystemExit(name + ": no capital in countries.json, write one")
            cap = "Its capital is %s." % c["capital"]
        al, seen = [], {modes.key(name)}
        for a in c.get("aliases", []) + extra:
            if modes.key(a) not in seen:
                seen.add(modes.key(a)); al.append(a)
        items.append({"id": "c" + c["iso2"], "n": name, "al": al, "clues": clues + [cap]})
    answer_keys = {modes.key(x) for p in items for x in [p["n"]] + p["al"]}
    decoys, dk = [], set()
    for c in countries:
        for d in [c["name"]] + c.get("aliases", []):
            k = modes.key(d)
            if k not in answer_keys and k not in dk:
                dk.add(k); decoys.append(d)
    for d in EXTRA_DECOYS:
        k = modes.key(d)
        if k not in answer_keys and k not in dk:
            dk.add(k); decoys.append(d)
    doc = {"about": "Guess the country. Five clues each, hardest first, the capital last; 5 points from the "
                    "first clue down to 1. Decoys are other real places, so they never count as typos. "
                    "Generated by tools/content/gen_clues.py from clues_src.py - edit there.",
           "items": items, "decoys": decoys}
    out = os.path.join(ROOT, "docs", "clues.json")
    with open(out, "w", encoding="utf-8") as f:
        f.write(json.dumps(doc, indent=0, ensure_ascii=False) + "\n")
    print(len(items), "countries,", len(decoys), "decoys ->", os.path.normpath(out))


if __name__ == "__main__":
    main()
